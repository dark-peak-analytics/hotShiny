# Regenerate NAMESPACE.
#
# hotShiny re-exports shiny's whole API (so `library(hotShiny)` is a drop-in
# for `library(shiny)`), except the functions it implements itself. Run from
# the package root:  Rscript tools/update-namespace.R
own <- function() {
  exprs <- unlist(lapply(list.files("R", full.names = TRUE), function(f) {
    lines <- readLines(f)
    ex <- grep("^#' @export", lines)
    vapply(ex, function(i) {
      j <- i + 1
      while (j <= length(lines) && grepl("^#'", lines[j])) j <- j + 1
      sub("^`?([^` ]+)`?\\s*<-.*$", "\\1", lines[j])
    }, "")
  }))
  unique(exprs)
}
mine <- own()
s3 <- grep("^(\\$|\\[\\[|\\[|\\$<-|\\[\\[<-|\\[<-|names|print|str|format)\\.", mine, value = TRUE)
fns <- setdiff(mine, s3)
shiny_exports <- sort(getNamespaceExports("shiny"))
reexports <- setdiff(shiny_exports, fns)

split_s3 <- function(m) {
  for (g in c("$<-", "[[<-", "[<-", "[[", "$", "[", "names", "print", "str", "format")) {
    if (startsWith(m, paste0(g, "."))) return(c(g, substring(m, nchar(g) + 2)))
  }
  stop("bad S3 method ", m)
}
q <- function(x) if (grepl("^[A-Za-z.][A-Za-z0-9._]*$", x)) x else paste0("\"", x, "\"")

out <- c(
  "# Generated by tools/update-namespace.R: do not edit by hand",
  "",
  "# hotShiny's own API",
  sprintf("export(%s)", vapply(sort(fns), q, "")),
  "",
  "# S3 methods",
  vapply(sort(s3), function(m) { p <- split_s3(m); sprintf("S3method(%s,%s)", q(p[1]), p[2]) }, ""),
  "",
  "# Imports",
  "importFrom(R6,R6Class)",
  "importFrom(fastmap,fastmap)",
  "importFrom(cachem,cache_mem)",
  "importFrom(jsonlite,fromJSON)",
  "importFrom(base64enc,base64encode)",
  "importFrom(tools,file_ext)",
  "",
  "# Re-exported from shiny (identical UI and helpers)",
  sprintf("importFrom(shiny,%s)", vapply(reexports, q, "")),
  sprintf("export(%s)", vapply(reexports, q, "")),
  ""
)
writeLines(out, "NAMESPACE")
cat("NAMESPACE: ", length(fns), " own exports, ", length(s3), " S3 methods, ",
    length(reexports), " shiny re-exports\n", sep = "")

# Standard "objects exported from other packages" page for the re-exports.
esc <- function(x) gsub("([%{}\\\\])", "\\\\\\1", x)
rd <- c(
  "% Generated by tools/update-namespace.R: do not edit by hand",
  "\\docType{import}",
  "\\name{reexports}",
  "\\alias{reexports}",
  paste0("\\alias{", esc(reexports), "}"),
  "\\title{Objects exported from other packages}",
  "\\keyword{internal}",
  "\\description{",
  "These objects are imported from other packages. Follow the links",
  "below to see their documentation.",
  "",
  "\\describe{",
  paste0("  \\item{shiny}{", paste0("\\code{\\link[shiny:", esc(reexports), "]{", esc(reexports), "}}", collapse = ", "), "}"),
  "}}"
)
writeLines(rd, "man/reexports.Rd")
